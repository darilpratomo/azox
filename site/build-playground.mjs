// Bundles the Azox compiler into a single browser module for the
// playground.
//
// It reads the real compiler sources rather than keeping a copy, so
// the playground cannot drift from the framework it demonstrates. A
// test asserts the compiler stays free of Node built-ins, which is
// what makes this possible at all.
//
// This is a flat concatenation, not a general bundler: the module
// graph is small, known, and acyclic, so the order below is enough.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(SITE_DIR, '..');

// Dependency order: each file may only use what came before it.
const MODULES = [
  'core/buildError.js',
  'core/compiler/html.js',
  'core/compiler/parser.js',
  'core/compiler/sourceResolver.js',
  // resolveComponents imports the scoping helpers; left out, the
  // playground fails to parse the whole bundle.
  'core/compiler/scopeStyles.js',
  'core/compiler/resolveComponents.js',
  'core/compiler/compileToJs.js',
  // renderToHtml imports evaluateScript from here. Left out, every
  // example with a stateful component failed with "evaluateScript is
  // not defined" — which is the playground's own default example.
  'core/renderer/serverScope.js',
  'core/renderer/renderToHtml.js',
];

// Names the playground calls directly.
const EXPORTS = [
  'parseAzox',
  'resolveComponents',
  'compileToModule',
  'renderToHtml',
  'createMemoryResolver',
  'BuildError',
  // The playground evaluates page scripts the way the build does,
  // rather than keeping a second implementation that drifts.
  'evaluateScript',
];

function stripModuleSyntax(source) {
  return (
    source
      // Imports are resolved by concatenation order instead.
      .replace(/^import\s[^;]*;\s*$/gm, '')
      // Keep the declarations, drop the export keyword.
      .replace(/^export\s+(?=(function|const|let|class))/gm, '')
      .replace(/^export\s+\{[^}]*\}\s*;?\s*$/gm, '')
  );
}

const parts = MODULES.map((path) => {
  const source = readFileSync(resolve(ROOT, path), 'utf8');
  return `// ---- ${path} ----\n${stripModuleSyntax(source).trim()}`;
});

const bundle = `// Generated by site/build-playground.mjs — do not edit.
// The Azox compiler, assembled from core/ for use in the browser.

${parts.join('\n\n')}

export { ${EXPORTS.join(', ')} };
`;

const outPath = resolve(SITE_DIR, 'public/azox-compiler.js');
writeFileSync(outPath, bundle, 'utf8');

console.log(`Wrote ${outPath} (${(bundle.length / 1024).toFixed(1)} kB)`);
